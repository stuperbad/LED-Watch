"""Generate firmware/pins.h and firmware/ledmap.h from the schematic netlist (schematic/n_solar.xml), so the firmware can never disagree with the board.
   python firmware/gen_pins.py
pins.h   : which MCU pin (port + bit) every signal is wired to
ledmap.h : for every LED (hour 0-11, minute 0-59, second 0-59, mode 0-5) the matrix ROW and COLUMN it sits on
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
root = ET.parse(HERE.parent / "schematic" / "n_solar.xml").getroot()

# pin number -> name of the MCU symbol
names = {}
for lp in root.find("libparts"):
    if lp.get("part", "").startswith("AVR128DB48"):
        for p in lp.find("pins"):
            names[p.get("num")] = p.get("name")

sig = {}                      # signal -> (pin number, pin name)
leds = {}                     # ref -> {"row": n, "col": n}
for net in root.find("nets"):
    nm = net.get("name").lstrip("/")
    for node in net:
        ref, pin = node.get("ref"), node.get("pin")
        if ref == "U1" and not nm.startswith("unconnected") and nm not in ("VBAT", "GND"):
            sig[nm] = (pin, names.get(pin, "?"))
        if re.fullmatch(r"[HMS]\d+|IND\d", ref):
            m = re.fullmatch(r"(ROW|COL)(\d+)", nm)
            if m:
                leds.setdefault(ref, {})[m.group(1).lower()] = int(m.group(2))

def port(name):
    m = re.search(r"P([A-G])(\d)", name)
    return (m.group(1), int(m.group(2))) if m else (None, None)

lines = ["// GENERATED by firmware/gen_pins.py from schematic/n_solar.xml - do not edit by hand",
         "#pragma once", "",
         "// signal                      port  bit   (MCU pin number, name)"]
for s_, (pin, nm) in sorted(sig.items(), key=lambda kv: (kv[0][:3] != "ROW", kv[0][:3] != "COL", int(re.sub(r"\D", "", kv[0]) or 0), kv[0])):
    pt, bit = port(nm)
    if pt:
        lines.append(f"#define PIN_{s_:<16s} PORT{pt}, {bit}   // pin {pin}  {nm}")
    else:
        lines.append(f"// {s_:<22s} pin {pin}  {nm}")
(HERE / "pins.h").write_text("\n".join(lines) + "\n", encoding="utf8")

# hwmap.h: the same wiring as plain numbers, so the C hardware layer can build its port masks at compile time and check its assumptions
hw = ["// GENERATED by firmware/gen_pins.py from schematic/n_solar.xml - do not edit by hand", "#pragma once", "",
      "// every signal the hardware layer uses: port letter and bit number", ""]
for s_, (pin, nm) in sorted(sig.items()):
    pt, bit = port(nm)
    if pt and re.fullmatch(r"ROW\d+|COL\d+_MCU|BTN\d|IMU_INT|BAT_OK|SCL|SDA", s_):
        key = s_.replace("_MCU", "")
        hw.append(f"#define HW_{key}_PORT '{pt}'")
        hw.append(f"#define HW_{key}_BIT {bit}")
(HERE / "hwmap.h").write_text("\n".join(hw) + "\n", encoding="utf8")

def idx(ref):
    return int(re.sub(r"\D", "", ref))

out = ["// GENERATED by firmware/gen_pins.py - do not edit by hand",
       "#pragma once", "#include <stdint.h>", "",
       "// matrix position of every LED: column = 30-degree sector (COL0..COL11 = 12 o'clock sector first), row = ring slot (ROW0 hour, ROW1-5 minute, ROW6-10 second, ROW11 mode LEDs)",
       "typedef struct { uint8_t row, col; } led_pos_t;"]
for prefix, name, n in (("H", "HOUR_LED", 12), ("M", "MINUTE_LED", 60), ("S", "SECOND_LED", 60), ("IND", "MODE_LED", 6)):
    arr = []
    for i in range(n):
        ref = f"H{i if i else 12}" if prefix == "H" else f"IND{i + 1}" if prefix == "IND" else f"{prefix}{i}"   # IND1..IND6 are 1-based
        d = leds.get(ref)
        arr.append("{%d,%d}" % (d["row"], d["col"]) if d and "row" in d and "col" in d else "{255,255}")
    out.append(f"static const led_pos_t {name}[{n}] = {{ " + ", ".join(arr) + " };")
(HERE / "ledmap.h").write_text("\n".join(out) + "\n", encoding="utf8")
print("wrote pins.h (", len(sig), "signals ) and ledmap.h (", len(leds), "LEDs )")
